import { describe, it, expect, beforeEach, vi } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { AIAssistantDrawer } from '../components/AIAssistantDrawer';
import { createDefaultEventPlan } from '../services/plannerGenerator';
import { copilotRateLimiter } from '../services/aiCopilot';

beforeEach(() => {
  copilotRateLimiter.reset();
  Element.prototype.scrollIntoView = vi.fn();
});

const openDrawer = () => fireEvent.click(screen.getByRole('button', { name: /Open AI Event Copilot/i }));

describe('AIAssistantDrawer', () => {
  it('greets with the current plan, not a stale one', () => {
    const plan = createDefaultEventPlan();
    const { rerender } = render(<AIAssistantDrawer plan={plan} apiKey="" />);
    openDrawer();
    expect(screen.getByText(new RegExp(plan.title))).toBeInTheDocument();

    rerender(<AIAssistantDrawer plan={{ ...plan, title: 'Riya Rooftop Bash' }} apiKey="" />);
    expect(screen.getByText(/Riya Rooftop Bash/)).toBeInTheDocument();
  });

  it('renders markdown answers as formatted elements instead of raw asterisks', async () => {
    render(<AIAssistantDrawer plan={createDefaultEventPlan()} apiKey="" />);
    openDrawer();
    fireEvent.change(screen.getByRole('textbox', { name: /Message to event planner copilot/i }), {
      target: { value: 'rain backup plan?' },
    });
    fireEvent.click(screen.getByRole('button', { name: /Send message/i }));

    const heading = await screen.findByText(/Contingency & Weather Defense Plan/);
    expect(heading.tagName).toBe('STRONG');
    expect(screen.queryByText(/\*\*Contingency/)).not.toBeInTheDocument();
    expect(screen.getByText(/Offline engine/)).toBeInTheDocument();
  });

  it('exposes the conversation as a polite live region and caps input length', () => {
    render(<AIAssistantDrawer plan={createDefaultEventPlan()} apiKey="" />);
    openDrawer();
    expect(screen.getByRole('log')).toHaveAttribute('aria-live', 'polite');
    expect(screen.getByRole('textbox', { name: /Message to event planner copilot/i })).toHaveAttribute('maxLength', '500');
  });

  it('closes on Escape and returns focus to the trigger', async () => {
    render(<AIAssistantDrawer plan={createDefaultEventPlan()} apiKey="" />);
    openDrawer();
    fireEvent.keyDown(document, { key: 'Escape' });
    await waitFor(() => expect(screen.queryByRole('log')).not.toBeInTheDocument());
    await waitFor(() => expect(screen.getByRole('button', { name: /Open AI Event Copilot/i })).toHaveFocus());
  });

  it('shows the live Gemini badge when a key is configured', () => {
    render(<AIAssistantDrawer plan={createDefaultEventPlan()} apiKey="AIzaSyTEST-key-1234567890" />);
    openDrawer();
    expect(screen.getByText(/Live gemini-2.5-flash/)).toBeInTheDocument();
  });
});

describe('AIAssistantDrawer with live Gemini', () => {
  it('shows the Gemini answer and the exact prompt that was sent', async () => {
    vi.stubGlobal(
      'fetch',
      vi.fn().mockResolvedValue({
        ok: true,
        status: 200,
        json: async () => ({ candidates: [{ content: { parts: [{ text: '**Rooftop rain plan**\n- Book a tent' }] } }] }),
      })
    );
    render(<AIAssistantDrawer plan={createDefaultEventPlan()} apiKey="AIzaSyTEST-key-1234567890" />);
    openDrawer();
    fireEvent.change(screen.getByRole('textbox', { name: /Message to event planner copilot/i }), {
      target: { value: 'Rain plan?' },
    });
    fireEvent.click(screen.getByRole('button', { name: /Send message/i }));

    expect(await screen.findByText('Rooftop rain plan')).toBeInTheDocument();
    expect(screen.getByText(/Generated by Gemini/)).toBeInTheDocument();
    expect(screen.getByText('View prompt sent to Gemini')).toBeInTheDocument();
    expect(screen.getByText(/<user_question>Rain plan\?<\/user_question>/)).toBeInTheDocument();
    vi.unstubAllGlobals();
  });
});
